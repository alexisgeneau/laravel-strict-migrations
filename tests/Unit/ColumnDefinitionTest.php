<?php

declare(strict_types=1);

use StrictMigrations\Operations\ColumnDefinition;
use StrictMigrations\Sql\Dialect;
use StrictMigrations\Sql\Tokens;

function definition(string $sql, Dialect $dialect = Dialect::Postgres): ColumnDefinition
{
    return ColumnDefinition::parse(Tokens::of($sql, $dialect));
}

it('reads a column definition', function (string $sql, Dialect $dialect, array $properties) {
    expect(definition($sql, $dialect))->toHaveProperties($properties);
})->with([
    ["varchar(255) not null default 'new'", Dialect::Postgres, ['type' => 'varchar(255)', 'nullable' => false, 'default' => "'new'"]],
    ['numeric(10, 2) null', Dialect::Postgres, ['type' => 'numeric(10,2)', 'nullable' => true, 'default' => null]],
    ['timestamp(0) without time zone null default CURRENT_TIMESTAMP', Dialect::Postgres, ['type' => 'timestamp(0) without time zone', 'default' => 'CURRENT_TIMESTAMP']],
    ['bigserial not null primary key', Dialect::Postgres, ['type' => 'bigserial', 'autoIncrement' => true, 'primary' => true]],
    ['integer generated by default as identity', Dialect::Postgres, ['autoIncrement' => true]],
    ['varchar generated always as (lower(email)) stored', Dialect::Postgres, ['type' => 'varchar', 'generated' => 'stored']],
    ['integer[] not null', Dialect::Postgres, ['type' => 'integer[]']],
    ['bigint unsigned not null auto_increment primary key', Dialect::MySql, ['type' => 'bigint unsigned', 'autoIncrement' => true, 'primary' => true]],
    ["varchar(50) character set latin1 collate 'latin1_swedish_ci' null after `code`", Dialect::MySql, ['type' => 'varchar(50)', 'charset' => 'latin1', 'collation' => 'latin1_swedish_ci', 'positioned' => true]],
    ["enum('low', 'high') not null default 'low'", Dialect::MySql, ['type' => "enum('low','high')", 'default' => "'low'"]],
    ['decimal(10, 2) as (total * 1.2) virtual', Dialect::MySql, ['generated' => 'virtual']],
    ['timestamp null on update CURRENT_TIMESTAMP', Dialect::MySql, ['type' => 'timestamp', 'nullable' => true]],
    ['varchar(36) not null default (uuid()) unique', Dialect::MySql, ['default' => '(uuid())', 'unique' => true]],
]);

it('tells whether a default is computed for every row', function (string $sql, bool $volatile, bool $expression, bool $nonConstant) {
    $definition = definition($sql);

    expect($definition->volatileDefault())->toBe($volatile)
        ->and($definition->expressionDefault())->toBe($expression)
        ->and($definition->nonConstantDefault())->toBe($nonConstant);
})->with([
    'a constant' => ["varchar default 'x'", false, false, false],
    'now()' => ['timestamptz default now()', false, false, false],
    'CURRENT_TIMESTAMP' => ['timestamptz default CURRENT_TIMESTAMP', false, false, true],
    'gen_random_uuid()' => ['uuid default gen_random_uuid()', true, false, false],
    'clock_timestamp()' => ['timestamptz default clock_timestamp()', true, false, false],
    'an expression' => ['varchar(36) default (uuid())', true, true, true],
]);
